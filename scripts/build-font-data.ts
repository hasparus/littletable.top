// Writes src/ops/text/font-data.generated.ts: tldraw's own font files (from
// @tldraw/assets, the version the client ships) as base64, for the
// server-side text measurer. Run it after a tldraw update:
//
//   node scripts/build-font-data.ts

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const fonts = join(dirname(require.resolve("@tldraw/assets/package.json")), "fonts");
const version = (require("@tldraw/assets/package.json") as { version: string }).version;

// The faces tldraw's default fonts use (tldraw's defaultFonts.tsx): the
// family's normal and bold weights. Italic falls back to these.
const FACES = {
  "draw/bold": "Shantell_Sans-Informal_Bold.woff2",
  "draw/normal": "Shantell_Sans-Informal_Regular.woff2",
  "mono/bold": "IBMPlexMono-Bold.woff2",
  "mono/normal": "IBMPlexMono-Medium.woff2",
  "sans/bold": "IBMPlexSans-Bold.woff2",
  "sans/normal": "IBMPlexSans-Medium.woff2",
  "serif/bold": "IBMPlexSerif-Bold.woff2",
  "serif/normal": "IBMPlexSerif-Medium.woff2",
};

const entries = Object.entries(FACES).map(
  ([face, file]) => `  "${face}": "${readFileSync(join(fonts, file)).toString("base64")}",`,
);

writeFileSync(
  new URL("../src/ops/text/font-data.generated.ts", import.meta.url),
  [
    `// Generated by scripts/build-font-data.ts from @tldraw/assets ${version}. Do not edit.`,
    "// The fonts are under the SIL Open Font License (Shantell Sans, IBM Plex).",
    "export const FONT_DATA: Record<string, string> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);
